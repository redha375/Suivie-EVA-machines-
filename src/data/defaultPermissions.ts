// Helper to generate full permission set for a role
const createAllTrue = (): Record<PermissionResource, Record<PermissionAction, boolean>> => {
  const result = {} as Record<PermissionResource, Record<PermissionAction, boolean>>;
  for (const res of ALL_RESOURCES) {
    result[res] = {
      read: true,
      create: true,
      update: true,
      deactivate: true,
      delete: true,
      validate: true,
      export: true,
    };
  }
  return result;
};

const createCustomPerms = (
  rules: Partial<Record<PermissionResource, Partial<Record<PermissionAction, boolean>>>>,
  defaultVal = false
): Record<PermissionResource, Record<PermissionAction, boolean>> => {
  const result = {} as Record<PermissionResource, Record<PermissionAction, boolean>>;
  for (const res of ALL_RESOURCES) {
    result[res] = {
      read: defaultVal,
      create: defaultVal,
      update: defaultVal,
      deactivate: defaultVal,
      delete: defaultVal,
      validate: defaultVal,
      export: defaultVal,
    };
    if (rules[res]) {
      result[res] = { ...result[res], ...rules[res] };
    }
  }
  return result;
};

